// Lane A, hard mode: attack the OPEN problem — is minimum attractor NP-hard at sigma = 2?
// Three angles in parallel, then a synthesis, then an adversarial review.
const ROOT = "/home/bot/sortbounds";
const H4 = 4 * 60 * 60 * 1000;
const H2 = 2 * 60 * 60 * 1000;

const RULES = [
  `Repository ${ROOT}. READ AGENTS.md and docs/research/hardness-attractor.md + hardness-related-binary.md (they establish that the sigma = 2 case is OPEN: no source proves hardness, none gives an algorithm).`,
  `You are attacking an OPEN problem. The bar is different from a literature note:`,
  `  * every claim must be labelled PROVED / COMPUTATIONALLY-CHECKED / MY-CONJECTURE / UNVERIFIED;`,
  `  * a hand-built reduction is NOT credible until its equivalence claim is checked exhaustively on small source instances;`,
  `  * a failed attempt is a result IF it is precisely characterised (which step breaks, on which instance);`,
  `  * never fabricate: no theorem, no number, no quote without a source or a reproducible command.`,
  `Python: stdlib only, 'timeout' on every run, assert progress in every loop. Do not run git.`,
  `Do not edit files outside your assigned path.`,
].join("\n");

const gadget = await runs.run("gadget", {
  label: "Build and TEST a binary-alphabet reduction",
  agent: "worker",
  timeoutMs: H4,
  cwd: ROOT,
  output: "sigma2-gadget.md",
  task: [
    RULES,
    `You own EXACTLY ONE directory: tools/sigma2/ (plus the report sigma2-gadget.md).`,
    ``,
    `MISSION: construct a polynomial-time reduction from a known NP-hard problem to`,
    `"minimum attractor of a BINARY string", and TEST it exhaustively on small instances.`,
    `Suggested sources (pick the most promising and say why): 3-SAT, 3-dimensional matching,`,
    `set cover with bounded sets, vertex cover, partition, or minimum-LZ77-phrase (whose hardness`,
    `proofs already have small-alphabet gadget experience — steal the gadget style).`,
    `Requirements:`,
    `1. state the source problem and the reduction explicitly (an algorithm that maps an instance`,
    `   to a binary string, with its size bound);`,
    `2. state the equivalence claim precisely (e.g. "OPT(C) <= q iff gamma_k(T_C) <= B(q)"), including`,
    `   the role of k (fixed? growing? k = n?) — hardness at fixed k does not give hardness at k = n;`,
    `3. IMPLEMENT the reduction and CHECK the claim exhaustively on ALL source instances below a`,
    `   size you can afford (e.g. all 3-SAT instances with <= 4 variables and <= 6 clauses): compute`,
    `   the source optimum by brute force, build T_C, compute gamma_k(T_C) exactly (use`,
    `   tools/attractor/anytime.py's certified search, or exhaustive search for the small n involved),`,
    `   and assert the claimed correspondence. Report the number of instances checked and every`,
    `   failure with its witness.`,
    `4. If the check fails, do not patch the claim silently: report the smallest counterexample and`,
    `   what it implies about the gadget (this is the most valuable output if it happens).`,
    `Deliverables: tools/sigma2/{reduce.py, check.py, README.md} and sigma2-gadget.md with the`,
    `reduction, the checked results, and an explicit "what remains unproved" (the general-direction`,
    `argument, and any step the exhaustive check cannot reach). No claim of NP-hardness unless the`,
    `reduction is complete AND the equivalence is either proved or checked with a stated scope.`,
  ].join("\n"),
});

const alg = await runs.run("alg", {
  label: "Hunt for structure that makes binary instances tractable",
  agent: "worker",
  timeoutMs: H4,
  cwd: ROOT,
  output: "sigma2-algorithm.md",
  task: [
    RULES,
    `You own EXACTLY ONE directory: tools/sigma2-alg/ (plus the report sigma2-algorithm.md).`,
    ``,
    `MISSION: the opposite bet — that at sigma = 2 the minimum attractor is computable. Find the`,
    `structure, and test it.`,
    `Concretely: compute gamma EXACTLY for every binary string up to the largest n your budget`,
    `allows (use tools/attractor/anytime.py; report gamma ONLY when the certified bracket is closed),`,
    `together with a battery of structural features: n, delta (exact fraction), the d_k profile,`,
    `gamma_1, gamma_2 (exact 2-attractor, polynomial at sigma = 2), the number of distinct factors`,
    `of each length, the run structure (number of runs, max run), the period, the shortest distance`,
    `between two occurrences of the least frequent symbol, and the packing bound.`,
    `Then test, with numbers:`,
    `1. Is gamma a FUNCTION of a few of those features? (Train nothing — look for exact functional`,
    `   dependence: if two strings have the same feature vector and different gamma, that kills it.)`,
    `2. Is gamma <= gamma_2 + c or gamma <= ceil(delta) + c with a small c? Report the worst case.`,
    `3. Does an exact algorithm fall out of the structure — e.g. dynamic programming over a`,
    `   different parameterisation (number of runs, number of distinct factors, or the "profile"`,
    `   of gamma_k for small k)? If you find one, IMPLEMENT it and check it against exhaustive`,
    `   gamma on all binary strings up to your n; if it fails, give the smallest counterexample.`,
    `Deliverables: tools/sigma2-alg/{features.py, check.py, README.md}, the report with a table of`,
    `what determines gamma and what does not, and an explicit verdict: "binary looks tractable`,
    `via X" (with the algorithm and its checked scope) or "no structure found; here is what failed".`,
  ].join("\n"),
});

const lit = await runs.run("lit", {
  label: "Mine the neighbour reductions for binary-alphabet gadget technique",
  agent: "worker",
  timeoutMs: H4,
  cwd: ROOT,
  output: "sigma2-technique.md",
  task: [
    RULES,
    `You own EXACTLY ONE file: docs/research/sigma2-technique.md.`,
    ``,
    `MISSION: the closest neighbours to minimum-attractor are minimum SLP (g) and minimum LZ77`,
    `phrases (z), and gamma <= g and gamma <= z. Their hardness proofs are the best available`,
    `source of BINARY-alphabet gadget technique.`,
    `1. For each of: smallest grammar / SLP (Charikar et al. 2005 and successors), minimum LZ77`,
    `   parsing (and its approximation results), minimum macro scheme / bidirectional (b), and the`,
    `   "k-attractor"; report VERBATIM: the hardness statement, the source problem, and — the`,
    `   crux — the alphabet size used. Quote the sentence that fixes the alphabet.`,
    `2. For every reduction whose gadget you can read, describe the gadget mechanism in enough`,
    `   detail that someone could transplant it to attractors: what plays the role of "variable",`,
    `   "clause", "satisfaction", and how the string encodes choices. Note explicitly whether the`,
    `   gadget needs sigma_k distinct symbols (and what breaks at sigma_k = 2).`,
    `3. Say what a binary-alphabet attractor reduction would most plausibly look like, and which`,
    `   technical obstacle the neighbour proofs do NOT solve.`,
    `4. Flag any place where gamma <= g or gamma <= z turns a neighbour's hardness into an`,
    `   attractor hardness — and be careful about direction (an upper bound on gamma does NOT`,
    `   inherit hardness from g).`,
    `<= 1800 words. Every claim labelled; quote, do not paraphrase, when the alphabet is at issue.`,
  ].join("\n"),
});

const synth = await runs.run("synth", {
  label: "Synthesise lane A-hard into one claim set",
  agent: "worker",
  timeoutMs: H2,
  cwd: ROOT,
  output: "docs/research/sigma2-hardness-attempt.md",
  task: [
    RULES,
    `You own EXACTLY ONE file: docs/research/sigma2-hardness-attempt.md.`,
    `Three workers just attacked the OPEN question "is minimum attractor NP-hard at sigma = 2?"`,
    `Their reports are in the repo: docs/research/sigma2-technique.md, and (in the run's artifact`,
    `area, copied to the repo by the integrator) sigma2-gadget.md, sigma2-algorithm.md. Read all`,
    `three, plus docs/research/hardness-attractor.md.`,
    `Write the synthesis as a claim register:`,
    `1. "What is now established" — only statements that are PROVED or COMPUTATIONALLY-CHECKED,`,
    `   each with its scope (how many instances, which n, which k) and a pointer to the artifact;`,
    `2. "What failed and why" — every reduction or algorithm that broke, with its smallest`,
    `   counterexample and the structural reason;`,
    `3. "The strongest true statement about sigma = 2 today" — one paragraph, no overclaim: if the`,
    `   reduction is incomplete, say which step is missing and what would close it;`,
    `4. "Next three experiments", each with a concrete command and a decision criterion.`,
    `Be ruthless about the difference between "checked on all instances with n <= 10" and "proved".`,
    `<= 1500 words.`,
  ].join("\n"),
});

const rev = await runs.run("review", {
  label: "Adversarial review of the sigma=2 attack",
  agent: "reviewer",
  timeoutMs: H2,
  cwd: ROOT,
  task: [
    `Read-only review in ${ROOT}. Do not edit, do not git. You MAY run 'timeout 300 python3`,
    `tools/sigma2/check.py' and 'timeout 300 python3 tools/sigma2-alg/check.py'.`,
    `Scope: docs/research/sigma2-hardness-attempt.md, docs/research/sigma2-technique.md,`,
    `tools/sigma2/, tools/sigma2-alg/.`,
    `This lane attacked an OPEN problem. Audit it as a hostile referee would:`,
    `1. Is any reduction claim actually a reduction (a size-bounded map with a PROVED or`,
    `   systematically-checked equivalence), or is it a gadget sketch dressed as a theorem?`,
    `2. Does the equivalence check test the RIGHT claim — the iff, at the right k, on instances`,
    `   where the source optimum actually varies (not only on satisfiable or only on unsat ones)?`,
    `3. If an algorithm is claimed, is it a real algorithm with a checked scope, or a heuristic`,
    `   that agrees on small n? Is its complexity stated?`,
    `4. Is anything labelled PROVED that is really MY-CONJECTURE or COMPUTATIONALLY-CHECKED?`,
    `5. Does the synthesis overclaim "sigma = 2 is answered"? It is not, unless a complete`,
    `   reduction or a proved algorithm is present.`,
    `Output: numbered PASS/CONCERN/FAIL, then the exact sentences to change, and one verdict:`,
    `"claim safe as stated" or "claim must be weakened to X".`,
  ].join("\n"),
});

return { gadget: gadget.output, alg: alg.output, lit: lit.outputReference, synth: synth.outputReference, review: rev.output };
